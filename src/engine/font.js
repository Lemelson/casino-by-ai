const CW = 5, CH = 7;

export function drawText(g, text, x, y, color, opts = {}) {
  const scale = opts.scale || 1;
  const sp = opts.spacing == null ? 1 : opts.spacing;
  if (opts.shadow) {
    drawText(g, text, x + scale, y + scale, opts.shadow, { scale, spacing: sp });
  }
  let cx = Math.round(x);
  const ty = Math.round(y);
  for (const raw of String(text)) {
    let key = raw;
    let glyph = G[raw];
    if (!glyph) glyph = G[raw.toUpperCase()];
    if (raw === 'x') glyph = G.X_LOW; // строчный x для множителей "x3"
    if (!glyph) glyph = G['?'];
    if (raw !== ' ') {
      for (let r = 0; r < CH; r++) {
        const row = glyph[r];
        for (let c = 0; c < CW; c++) {
          if (row[c] === '#') g.rect(cx + c * scale, ty + r * scale, scale, scale, color);
        }
      }
    }
    cx += (CW + sp) * scale;
  }
  return cx;
}

export function textWidth(text, opts = {}) {
  const scale = opts.scale || 1;
  const sp = opts.spacing == null ? 1 : opts.spacing;
  const n = String(text).length;
  return n * (CW + sp) * scale - sp * scale;
}

export function drawTextCentered(g, text, cx, y, color, opts = {}) {
  return drawText(g, text, cx - textWidth(text, opts) / 2, y, color, opts);
}

// Текст с обводкой (8 направлений) — для крупных неоновых заголовков.
export function drawTextOutlined(g, text, x, y, color, outline, opts = {}) {
  const scale = opts.scale || 1;
  for (let dy = -scale; dy <= scale; dy += scale) {
    for (let dx = -scale; dx <= scale; dx += scale) {
      if (dx === 0 && dy === 0) continue;
      drawText(g, text, x + dx, y + dy, outline, opts);
    }
  }
  drawText(g, text, x, y, color, opts);
}

export function drawTextCenteredOutlined(g, text, cx, y, color, outline, opts = {}) {
  const x = cx - textWidth(text, opts) / 2;
  return drawTextOutlined(g, text, x, y, color, outline, opts);
}
